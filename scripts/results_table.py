"""Render README section 6 (results) from the files scripts/summarize.py and cost_report.py write.

    python scripts/results_table.py --status "preliminary: runs in progress at 2026-10-19 18:45 CDT"

Reads results/summary.csv, analysis/uncertainty.json, results/<group>/<bench>/<model>/per_task.csv and
logs/cost.json, and replaces the text between `<!-- results:begin -->` and `<!-- results:end -->` in
README.md. No number is typed by hand.
"""

import argparse
import csv
import json
import statistics as st
from datetime import datetime
from pathlib import Path

BENCH = [("swe_pro", "SWE-bench Pro v2-hard (HARD-51)"), ("tb2", "Terminal-Bench 2.0 (89 tasks)"),
         ("hle", "HLE (2,500)"), ("asi", "ASI-Bench (59 x 4 = 236)")]
MODELS = ["base", "swe", "term", "sci", "merged"]
GROUP = {"base": "base", "merged": "merged", "union": "controls"}
CONTROLS = ["union"]
STATUSES = ["ok", "agent_timeout", "llm_call_timeout", "env_error", "no_result"]


def per_task(model, bench):
    f = Path("results") / GROUP.get(model, "experts") / bench / model / "per_task.csv"
    return list(csv.DictReader(open(f))) if f.exists() else []


def fmt(x, nd=2):
    return "" if x is None else f"{x:.{nd}f}"


def cell(m, bench):
    if m is None:
        return "n/e"
    if bench == "tb2":
        n = m["n_complete_seeds"]
        if not n:
            return "no complete seed"
        sd = f" +- {m['seed_std']:.2f}" if n > 1 else ""
        return f"{m['primary']:.2f}{sd} ({n} seed{'s' if n > 1 else ''})"
    return fmt(m["primary"])


def minutes(rows, start="started_at", end="finished_at"):
    xs = []
    for r in rows:
        try:
            xs.append((datetime.fromisoformat(r[end].replace("Z", "+00:00")) -
                       datetime.fromisoformat(r[start].replace("Z", "+00:00"))).total_seconds() / 60)
        except (KeyError, ValueError, AttributeError):
            pass
    return st.mean(xs) if xs else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--status", required=True)
    a = ap.parse_args()
    unc = json.load(open("analysis/uncertainty.json"))
    met, boot = unc["metrics"], unc["paired_bootstrap_merged_minus_base"]
    cost = json.load(open("logs/cost.json")) if Path("logs/cost.json").exists() else {}
    L = [f"Status: **{a.status}**. Generated by `scripts/results_table.py` from `results/summary.csv`,",
         "`analysis/uncertainty.json` and the per-task CSVs; per-task results in `results/<group>/<benchmark>/<model>/`,",
         "failed-task lists in `results/failures/`.", "",
         "Primary metric, percent. Experts are evaluated on their target benchmarks only (n/e: not evaluated):",
         "swe on SWE-Pro, term on Terminal-Bench, sci on HLE and ASI-Bench. Terminal-Bench: mean +- std over",
         "complete seeds (all 89 tasks finished); partial seeds are listed below and are not in the mean.", "",
         "| Benchmark | Base | swe | term | sci | Merged | Merged - Base, pp (95% CI) |",
         "|---|---|---|---|---|---|---|"]
    for b, name in BENCH:
        row = [cell(met.get(f"{m}/{b}"), b) for m in MODELS]
        d = boot.get(b)
        dd = f"{d['diff_pp']:+.2f} [{d['ci95'][0]:+.2f}, {d['ci95'][1]:+.2f}] (n={d['n_tasks']})" if d else ""
        L.append(f"| {name} | " + " | ".join(row) + f" | {dd} |")
    base_macro = [met[f"base/{b}"]["primary"] for b, _ in BENCH if f"base/{b}" in met]
    mer_macro = [met[f"merged/{b}"]["primary"] for b, _ in BENCH if f"merged/{b}" in met]
    mac = unc.get("macro_merged_minus_base")
    if len(base_macro) == 4 and len(mer_macro) == 4 and mac:
        L.append(f"| Macro average (4 benchmarks, equal weight) | {st.mean(base_macro):.2f} | | | | "
                 f"{st.mean(mer_macro):.2f} | {mac['diff_pp']:+.2f} [{mac['ci95'][0]:+.2f}, {mac['ci95'][1]:+.2f}] |")
    L += ["",
          "Merged - Base is a paired bootstrap over the same tasks (10,000 resamples); Terminal-Bench uses complete",
          "seeds only; for ASI-Bench the paired difference is over all 236 instances with scorer-invalid instances",
          "scored 0 (the all-instances mean below), so it can differ slightly from the difference of the official means.",
          "The macro CI resamples tasks within each benchmark jointly. The exam's target is +3 pp (excellent +5 pp).", ""]

    u, ub = met.get("union/tb2"), unc.get("paired_bootstrap_union_tb2", {})
    if u:
        def ci(d):
            return f"{d['diff_pp']:+.2f} [{d['ci95'][0]:+.2f}, {d['ci95'][1]:+.2f}] (n={d['n_tasks']})" if d else ""
        L += ["**Control: union adapter** (one LoRA on all three training sets, section 4; not a merge), Terminal-Bench",
              "seed 1 only, same serving and harness; paired bootstrap against seed 1 of base and merged:", "",
              "| Model | Terminal-Bench 2.0 (89 tasks) | Union - Base, pp (95% CI) | Union - Merged, pp (95% CI) |",
              "|---|---|---|---|",
              f"| union (control) | {cell(u, 'tb2')} | {ci(ub.get('union_minus_base'))} | {ci(ub.get('union_minus_merged'))} |", ""]

    L += ["**Terminal-Bench seeds** (success rate, percent; incomplete seeds: tasks scored when the runners stopped, success on those):", "",
          "| Model | Complete seeds | Incomplete seeds |", "|---|---|---|"]
    for m in ("base", "term", "merged", "union"):
        t = met.get(f"{m}/tb2")
        if not t:
            continue
        full = ", ".join(f"{s}: {v:.2f}" for s, v in sorted(t["per_seed"].items())) or "none"
        part = ", ".join(f"{s}: {p['tasks_finished']}/89 finished, {p['success_on_finished']:.1f}"
                         for s, p in sorted(t["partial_seeds"].items())) or "none"
        L.append(f"| {m} | {full} | {part} |")
    L += ["", "The exam asks for 5 seeds per model; seeds 2-5 could not be completed in the compute available",
          "(section 5). The seed std of a single complete seed is not defined and is not reported.", "",
          "Repeat-run variation instead: seed 1 vs seed 2 on the tasks scored in both seeds (seed 2 incomplete):", ""]
    for m in ("base", "term", "merged"):
        by = {}
        for r in per_task(m, "tb2"):
            by.setdefault(r["task"], {})[r["run"]] = float(r["score"])
        both = [v for v in by.values() if "seed1" in v and "seed2" in v]
        if len(both) >= 20:
            s1, s2 = (100 * sum(v[k] for v in both) / len(both) for k in ("seed1", "seed2"))
            flip = sum(v["seed1"] != v["seed2"] for v in both)
            L.append(f"- {m}: {len(both)} tasks, seed 1 {s1:.1f}%, seed 2 {s2:.1f}%; outcome differs between seeds on {flip} tasks.")
    L.append("")

    L += ["**Run outcomes and failure rate** (every finished trial / question / instance; failures stay in the",
          "denominator and score 0). Failure rate = share not `ok`.", "",
          "| Model | Benchmark | n | ok | agent_timeout | llm_call_timeout | env_error | no_result | failure rate |",
          "|---|---|---|---|---|---|---|---|---|"]
    for m in MODELS + CONTROLS:
        for b, _ in BENCH:
            t = met.get(f"{m}/{b}")
            if not t:
                continue
            fc, n = t["failure_counts"], t["n_rows"]
            L.append(f"| {m} | {b} | {n} | " + " | ".join(str(fc.get(s, 0)) for s in STATUSES) +
                     f" | {100 * (n - fc.get('ok', 0)) / n:.1f}% |")
    L += ["", "Status meaning: TB2 `agent_timeout` = 3 h agent budget, `llm_call_timeout` = one model call over 600 s,",
          "`env_error` = container / exec-server failure; SWE-Pro rows are the patch_replay regrade (agent exits are",
          "in `analysis/failures.md`); HLE `no_result` = no final answer (32,768-token cap reached, or empty answer);",
          "ASI `no_result` = scorer-invalid instance (Docker-only validity gate, section 5).", ""]

    L += ["**Secondary metrics**", ""]
    for m in ("base", "sci", "merged"):
        h, s = met.get(f"{m}/hle"), met.get(f"{m}/asi")
        parts = []
        if h:
            parts.append(f"HLE text-only subset {h['text_only_subset_accuracy']:.2f}")
        if s:
            lv = ", ".join(f"{k} {v:.2f}" for k, v in s["per_level"].items())
            capped = sum(1 for r in per_task(m, "asi") if r.get("execution_s") and float(r["execution_s"]) >= 1795)
            parts.append(f"ASI all-instances mean {s['all_instances_mean']:.2f}; per level {lv}; "
                         f"scorer-invalid {s['scorer_error_count']}; agent stopped at the 1,800 s budget "
                         f"{capped}/{s['instance_count']} (graded as is)")
        if parts:
            L.append(f"- {m}: " + "; ".join(parts) + ".")
    L.append("")

    L += ["**Time and cost per task** (mean wall time; tokens are model tokens served by our vLLM, no API cost):", "",
          "| Model | Benchmark | mean time | mean output tokens |", "|---|---|---|---|"]
    for m in MODELS + CONTROLS:
        for b, _ in BENCH:
            rows = per_task(m, b)
            if not rows:
                continue
            if b in ("tb2", "swe_pro"):
                # SWE-Pro rows are the regrade; the agent trial's own times are carried along
                tm = minutes(rows, *(("agent_started_at", "agent_finished_at") if b == "swe_pro" else ()))
                tm = f"{tm:.1f} min / {'agent trial' if b == 'swe_pro' else 'trial'}" if tm is not None else ""
            elif b == "hle":
                xs = [float(r["latency_s"]) for r in rows if r.get("latency_s")]
                tm = f"{st.mean(xs):.0f} s / question" if xs else ""
            else:
                xs = [float(r["execution_s"]) for r in rows if r.get("execution_s")]
                tm = f"{st.mean(xs):.0f} s / instance (incl. sandbox setup)" if xs else ""
            toks = [float(r["output_tokens"]) for r in rows if r.get("output_tokens")]
            L.append(f"| {m} | {b} | {tm} | {st.mean(toks):,.0f} |" if toks else f"| {m} | {b} | {tm} | |")
    if cost:
        L += ["", f"Compute: HPC {'estimated ' if cost.get('hpc_su_is_estimate') else ''}{cost['hpc_su_charged']} SU "
              "(the project allocation; A100 GPU-hours: " + ", ".join(f"{k} {v}" for k, v in cost["hpc_gpu_hours_by_job_kind"].items()) +
              f"), seismic serving "
              f"{cost['seismic_eval_gpu_hours']} GPU-hours (`logs/eval_lanes.json`"
              + (f"; of which union control Terminal-Bench {cost['seismic_eval_gpu_hours_by_model']['union']}"
                 if "union" in cost.get("seismic_eval_gpu_hours_by_model", {}) else "") +
              "), cloud rental 0 USD. The HPC figure is an",
              "estimate because sacct cannot be fetched from seismic (`logs/hpc_sacct.txt` states how it was built).",
              "API cost: HLE judge o3-mini and ASI-Bench judge gpt-5.5 calls on the OpenAI API (usage not logged per call)."]
    readme = Path("README.md").read_text()
    i, j = readme.index("<!-- results:begin -->"), readme.index("<!-- results:end -->")
    Path("README.md").write_text(readme[:i] + "<!-- results:begin -->\n" + "\n".join(L) + "\n" + readme[j:])
    print("\n".join(L))


if __name__ == "__main__":
    main()
